using Microsoft.UI.Xaml;
using Microsoft.UI.Xaml.Controls;
using Microsoft.UI.Xaml.Data;
using Microsoft.UI.Xaml.Media;

namespace ServerMaster.Windows.Services;

/// <summary>
/// Translates literal interface text written in XAML. Bound values belong to the view model and
/// are left alone; text with no translation stays English. Translated text is never a key, so
/// running again over the same tree (after navigation or a dialog opens) changes nothing.
/// </summary>
public static class XamlTranslator
{
    public static void Apply(DependencyObject? root)
    {
        if (root is null || !Localization.Translates) return;
        var pending = new Stack<DependencyObject>();
        pending.Push(root);
        while (pending.Count > 0)
        {
            var element = pending.Pop();
            Translate(element);
            var count = VisualTreeHelper.GetChildrenCount(element);
            for (var index = 0; index < count; index++) pending.Push(VisualTreeHelper.GetChild(element, index));
            // Navigation items and flyouts are not always visual children of their owner.
            if (element is NavigationView navigation)
            {
                foreach (var item in navigation.MenuItems.Concat(navigation.FooterMenuItems).OfType<DependencyObject>()) pending.Push(item);
                if (navigation.PaneFooter is DependencyObject footer) pending.Push(footer);
            }
        }
    }

    /// <summary>Flyout menus are not in the visual tree until opened, so they translate on Opening.</summary>
    public static void ApplyMenu(MenuFlyout menu)
    {
        if (!Localization.Translates) return;
        foreach (var item in menu.Items.OfType<MenuFlyoutItem>())
            if (item.ReadLocalValue(MenuFlyoutItem.TextProperty) is not BindingExpression && Localization.TryTranslate(item.Text, out var text)) item.Text = text;
    }

    private static void Translate(DependencyObject element)
    {
        switch (element)
        {
            // Text generated by a ContentPresenter or an item container has no XAML parent and
            // may be user data (a table or profile name), so only authored text is considered.
            case TextBlock text when text.Parent is not null && text.Inlines.Count <= 1:
                Literal(text, TextBlock.TextProperty, text.Text, value => text.Text = value);
                break;
            case ContentDialog dialog:
                Literal(dialog, ContentDialog.TitleProperty, dialog.Title as string, value => dialog.Title = value);
                Literal(dialog, ContentDialog.PrimaryButtonTextProperty, dialog.PrimaryButtonText, value => dialog.PrimaryButtonText = value);
                Literal(dialog, ContentDialog.SecondaryButtonTextProperty, dialog.SecondaryButtonText, value => dialog.SecondaryButtonText = value);
                Literal(dialog, ContentDialog.CloseButtonTextProperty, dialog.CloseButtonText, value => dialog.CloseButtonText = value);
                if (dialog.Content is DependencyObject content) Apply(content);
                break;
            case ContentControl control when ItemsControl.ItemsControlFromItemContainer(control) is not { ItemsSource: not null }:
                Literal(control, ContentControl.ContentProperty, control.Content as string, value => control.Content = value);
                break;
        }
        switch (element)
        {
            case TextBox box:
                Literal(box, TextBox.HeaderProperty, box.Header as string, value => box.Header = value);
                Literal(box, TextBox.PlaceholderTextProperty, box.PlaceholderText, value => box.PlaceholderText = value);
                break;
            case NumberBox number:
                Literal(number, NumberBox.HeaderProperty, number.Header as string, value => number.Header = value);
                break;
            case ComboBox combo:
                Literal(combo, ComboBox.HeaderProperty, combo.Header as string, value => combo.Header = value);
                Literal(combo, ComboBox.PlaceholderTextProperty, combo.PlaceholderText, value => combo.PlaceholderText = value);
                foreach (var item in combo.Items.OfType<DependencyObject>()) Translate(item);
                break;
            case ToggleSwitch toggle:
                Literal(toggle, ToggleSwitch.HeaderProperty, toggle.Header as string, value => toggle.Header = value);
                break;
            case PasswordBox password:
                Literal(password, PasswordBox.HeaderProperty, password.Header as string, value => password.Header = value);
                break;
        }
        if (element.ReadLocalValue(Microsoft.UI.Xaml.Automation.AutomationProperties.NameProperty) is string name
            && Localization.TryTranslate(name, out var translatedName))
            Microsoft.UI.Xaml.Automation.AutomationProperties.SetName(element, translatedName);
        if (ToolTipService.GetToolTip(element) is string tip && Localization.TryTranslate(tip, out var translatedTip))
            ToolTipService.SetToolTip(element, translatedTip);
    }

    private static void Literal(DependencyObject owner, DependencyProperty property, string? value, Action<string> set)
    {
        if (string.IsNullOrEmpty(value) || owner.ReadLocalValue(property) is BindingExpression) return;
        if (Localization.TryTranslateDynamic(value, out var translated)) set(translated);
    }
}
